-- Investment proposals: the RM's advice, which the client accepts (and signs)
-- before it is turned into orders.

CREATE TABLE proposal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id    BIGINT        NOT NULL REFERENCES portfolio (id),
    title           VARCHAR(200)  NOT NULL,
    rationale       VARCHAR(4000),
    status          VARCHAR(24)   NOT NULL,   -- WORKING, SENT_FOR_VALIDATION, VALIDATED, REJECTED, EXECUTED
    created_by      VARCHAR(100)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at         TIMESTAMP WITH TIME ZONE,
    decided_at      TIMESTAMP WITH TIME ZONE,
    decided_by      VARCHAR(100),
    reject_reason   VARCHAR(500),
    signature_png   TEXT
);

CREATE INDEX idx_proposal_portfolio ON proposal (portfolio_id, created_at DESC);

CREATE TABLE proposal_line (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id    BIGINT         NOT NULL REFERENCES proposal (id) ON DELETE CASCADE,
    line_no        INTEGER        NOT NULL,
    instrument_id  BIGINT         NOT NULL REFERENCES instrument (id),
    side           VARCHAR(4)     NOT NULL,
    quantity       NUMERIC(19, 6) NOT NULL CHECK (quantity > 0),
    comment        VARCHAR(500)
);

ALTER TABLE trade_order
    ADD CONSTRAINT fk_order_proposal FOREIGN KEY (proposal_id) REFERENCES proposal (id);
