-- Orders on securities and listed derivatives, with the pre-trade check
-- results kept alongside for the audit trail.

CREATE TABLE trade_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id       BIGINT         NOT NULL REFERENCES portfolio (id),
    instrument_id      BIGINT         NOT NULL REFERENCES instrument (id),
    side               VARCHAR(4)     NOT NULL,     -- BUY, SELL
    quantity           NUMERIC(19, 6) NOT NULL CHECK (quantity > 0),
    limit_type         VARCHAR(12)    NOT NULL,     -- MARKET, LIMIT, STOP, STOP_LIMIT
    limit_price        NUMERIC(19, 6),
    stop_price         NUMERIC(19, 6),
    time_in_force      VARCHAR(4)     NOT NULL,     -- DAY, GTC, GTD
    valid_until        DATE,
    status             VARCHAR(20)    NOT NULL,     -- PENDING_APPROVAL, PLACED, FILLED, CANCELLED, REJECTED
    estimated_price    NUMERIC(19, 6) NOT NULL,
    gross_amount       NUMERIC(19, 2) NOT NULL,
    fees               NUMERIC(19, 2) NOT NULL,
    net_amount         NUMERIC(19, 2) NOT NULL,
    negotiated_fee     NUMERIC(19, 2),
    executed_price     NUMERIC(19, 6),
    executed_at        TIMESTAMP WITH TIME ZONE,
    check_summary      VARCHAR(2000),               -- the warnings that needed approval
    proposal_id        BIGINT,                      -- set when the order came from a proposal
    created_by         VARCHAR(100)   NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by         VARCHAR(100),                -- who approved / rejected / cancelled
    decided_at         TIMESTAMP WITH TIME ZONE,
    decision_note      VARCHAR(500)
);

CREATE INDEX idx_order_portfolio ON trade_order (portfolio_id, created_at DESC);
CREATE INDEX idx_order_status ON trade_order (status);
