-- MiFID II suitability profiles. Each review is one row; answers are one row
-- per question, so every version of a client's profile is kept.

CREATE TABLE mifid_profile (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id              BIGINT       NOT NULL REFERENCES client (id),
    questionnaire_version  VARCHAR(20)  NOT NULL,
    status                 VARCHAR(24)  NOT NULL,   -- IN_PROGRESS, PENDING_VALIDATION, VALID, SUPERSEDED, REFUSED, CANCELLED
    risk_score             INTEGER,                -- 1 (conservative) .. 5 (dynamic)
    complex_products_ok    BOOLEAN      NOT NULL DEFAULT FALSE,
    completion_percent     INTEGER     NOT NULL DEFAULT 0,
    client_decision        VARCHAR(16),             -- UNDER_REVIEW, ACCEPTED, REFUSED
    valid_until            DATE,
    signature_png          TEXT,                    -- data URL of the client's signature
    created_by             VARCHAR(100) NOT NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at           TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_mifid_profile_client ON mifid_profile (client_id, created_at DESC);

CREATE TABLE mifid_answer (
    profile_id   BIGINT      NOT NULL REFERENCES mifid_profile (id) ON DELETE CASCADE,
    question_id  VARCHAR(40) NOT NULL,
    option_id    VARCHAR(40) NOT NULL,
    PRIMARY KEY (profile_id, question_id)
);
