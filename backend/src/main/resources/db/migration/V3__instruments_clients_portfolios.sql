-- Security master, clients and portfolios.

CREATE TABLE instrument (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(32)  NOT NULL UNIQUE,      -- ISIN, or an internal code for derivatives
    name           VARCHAR(200) NOT NULL,
    asset_class    VARCHAR(16)  NOT NULL,             -- EQUITY, BOND, FUND, ETF, OPTION, FUTURE
    currency       VARCHAR(3)      NOT NULL,
    exchange       VARCHAR(32),
    risk_class     INTEGER     NOT NULL CHECK (risk_class BETWEEN 1 AND 7),
    complex        BOOLEAN      NOT NULL DEFAULT FALSE,
    last_price     NUMERIC(19, 6) NOT NULL,
    price_date     DATE         NOT NULL,
    -- Derivatives only
    underlying_id  BIGINT REFERENCES instrument (id),
    option_type    VARCHAR(4),                        -- CALL or PUT
    strike         NUMERIC(19, 6),
    expiry         DATE,
    contract_size  NUMERIC(19, 6)
);

CREATE INDEX idx_instrument_name ON instrument (lower(name));

CREATE TABLE client (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_number    VARCHAR(20)  NOT NULL UNIQUE,
    first_name       VARCHAR(100) NOT NULL,
    last_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(200),
    phone            VARCHAR(40),
    birth_date       DATE,
    country          VARCHAR(2)      NOT NULL,
    category         VARCHAR(32)  NOT NULL,           -- RETAIL, PROFESSIONAL, ELIGIBLE_COUNTERPARTY
    rm_username      VARCHAR(100) NOT NULL,           -- relationship manager (Keycloak username)
    portal_username  VARCHAR(100) UNIQUE,             -- the client's own login, if any
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX idx_client_rm ON client (rm_username);

CREATE TABLE portfolio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_number VARCHAR(20) NOT NULL UNIQUE,
    name            VARCHAR(120) NOT NULL,
    client_id       BIGINT       NOT NULL REFERENCES client (id),
    service_type    VARCHAR(20)  NOT NULL,            -- ADVISORY, DISCRETIONARY, EXECUTION_ONLY
    currency        VARCHAR(3)      NOT NULL,
    opened_on       DATE         NOT NULL
);

CREATE INDEX idx_portfolio_client ON portfolio (client_id);

CREATE TABLE cash_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id  BIGINT        NOT NULL REFERENCES portfolio (id),
    currency      VARCHAR(3)       NOT NULL,
    balance       NUMERIC(19, 2) NOT NULL,
    UNIQUE (portfolio_id, currency)
);

CREATE TABLE position (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id   BIGINT         NOT NULL REFERENCES portfolio (id),
    instrument_id  BIGINT         NOT NULL REFERENCES instrument (id),
    quantity       NUMERIC(19, 6) NOT NULL,           -- units; for bonds the nominal amount
    average_cost   NUMERIC(19, 6) NOT NULL,           -- per unit; for bonds % of nominal
    UNIQUE (portfolio_id, instrument_id)
);

-- Month-end performance index per portfolio (100 = start), for the chart.
CREATE TABLE valuation_history (
    portfolio_id  BIGINT        NOT NULL REFERENCES portfolio (id),
    as_of         DATE          NOT NULL,
    index_value   NUMERIC(12, 4) NOT NULL,
    PRIMARY KEY (portfolio_id, as_of)
);
