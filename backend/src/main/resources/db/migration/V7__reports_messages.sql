-- Generated statements / reports (PDF kept in the database for now; moves to
-- Azure Blob Storage at deployment) and client <-> RM secure messages.

CREATE TABLE report_job (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id   BIGINT        NOT NULL REFERENCES portfolio (id),
    report_type    VARCHAR(20)   NOT NULL,   -- STATEMENT, VALUATION, PERFORMANCE, TRANSACTIONS, COSTS
    status         VARCHAR(12)   NOT NULL,   -- PENDING, COMPLETED, FAILED
    requested_by   VARCHAR(100)  NOT NULL,
    requested_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at   TIMESTAMP WITH TIME ZONE,
    file_name      VARCHAR(200),
    content_base64 TEXT,                     -- the PDF, base64-encoded
    error          VARCHAR(1000)
);

CREATE INDEX idx_report_portfolio ON report_job (portfolio_id, requested_at DESC);

CREATE TABLE message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      BIGINT        NOT NULL REFERENCES client (id),   -- one conversation per client
    from_client    BOOLEAN       NOT NULL,
    sender         VARCHAR(100)  NOT NULL,
    sender_name    VARCHAR(200)  NOT NULL,
    body           VARCHAR(4000) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at        TIMESTAMP WITH TIME ZONE                         -- when the other side read it
);

CREATE INDEX idx_message_client ON message (client_id, created_at);
